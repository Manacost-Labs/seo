"""Regenerate the packaged hero lookup from the pinned HearthstoneJSON cards.json.
Usage: python tools/build-heroes.py dist/hs-cards-256589.json
Source: https://api.hearthstonejson.com/v1/256589/enUS/cards.json
"""
import hashlib
import json
import sys
from pathlib import Path

BUILD = 256589
SHA256 = "6246806e84755d85d764508d92dba76dd3c332bd7e5ceaee19a20f64d8cdb81f"
SLUGS = {slug.replace("-", "").upper(): slug for slug in (
    "death-knight", "demon-hunter", "druid", "hunter", "mage", "paladin",
    "priest", "rogue", "shaman", "warlock", "warrior",
)}

source = Path(sys.argv[1]).read_bytes()
if hashlib.sha256(source).hexdigest() != SHA256:
    raise ValueError(f"Expected cards.json for Hearthstone build {BUILD}")

heroes = {}
class_orders = {}
for card in json.loads(source):
    if card.get("type") != "HERO":
        continue
    if card.get("set") == "HERO_SKINS":
        classes = [card["cardClass"]]
    elif card["id"].startswith("TB_MultiClass_Hero_"):
        classes = card["classes"]
    else:
        continue
    # Heroes with the same set of classes must produce the same grouping key.
    key = int(card["dbfId"])
    if key in heroes or not classes:
        raise ValueError(f"Ambiguous hero {key}")
    members = tuple(SLUGS[value] for value in classes)
    order = class_orders.setdefault(frozenset(members), members)
    heroes[key] = " ".join(order)

width = max(len(str(key)) for key in heroes)
rows = "\n".join(f"\t\t{key:<{width}} => '{heroes[key]}'," for key in sorted(heroes))
target = Path(__file__).resolve().parents[1] / "indexpilot/src/Game/HeroCatalog.php"
target.write_text(f"""<?php
/**
 * Generated by tools/build-heroes.py from HearthstoneJSON build {BUILD}.
 *
 * @package IndexPilot
 */

declare( strict_types=1 );

namespace IndexPilot\\Game;

/** Deck hero DBF IDs and playable class slugs. */
final class HeroCatalog {{

	public const BUILD = {BUILD};

	public const CLASSES = array(
{rows}
	);
}}
""", encoding="utf-8", newline="\n")
print(f"{len(heroes)} heroes, build {BUILD}")
